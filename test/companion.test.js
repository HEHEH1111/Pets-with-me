const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { openStore, memoryCommand, messagesFor, askModel } = require('../core')

test('称呼可以覆盖，跨进程存储，删除后从上下文移除', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pets-with-me-'))
  t.after(() => fs.rmSync(dir,{recursive:true,force:true}))
  let store=openStore(dir)
  memoryCommand('以后叫我阿禾',store)
  memoryCommand('以后叫我小禾',store)
  memoryCommand('记住我喜欢桂花',store)
  assert.equal(memoryCommand('今天有点累',store),undefined)
  store=openStore(dir)
  assert.equal(store.get().memories.length,2)
  assert.equal(memoryCommand('你还记得怎么称呼我吗？',store),'你让我叫你小禾。')
  store.update(s=>{s.memories=s.memories.filter(m=>m.kind!=='name')})
  assert.equal(memoryCommand('我叫什么？',openStore(dir)),'你希望我怎么称呼你？')
  assert.doesNotMatch(messagesFor(store.get().memories,[],'你好')[0].content,/小禾/)
})
